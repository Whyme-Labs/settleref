"""Run against `npm run dev`. Requires Python Playwright and Chromium."""
import json
import os
from pathlib import Path
from playwright.sync_api import sync_playwright

out = Path('evidence')
out.mkdir(exist_ok=True)
checks = []
with sync_playwright() as p:
    executable = os.environ.get('BROWSER_EXECUTABLE')
    browser = p.chromium.launch(headless=True, **({'executable_path': executable} if executable else {}))
    context = browser.new_context(viewport={'width': 1440, 'height': 1100}, device_scale_factor=1)
    page = context.new_page()
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto('http://127.0.0.1:4173/', wait_until='networkidle')
    page.get_by_role('button', name='Load example').click()
    page.get_by_role('button', name='Review instruction').click()
    page.wait_for_function("document.querySelector('#t-review').classList.contains('complete')")
    assert page.get_by_role('button', name='Simulate settlement').is_disabled()
    checks.append('Review requires explicit confirmation before settlement')
    page.screenshot(path=str(out/'desktop-review.png'), full_page=True)
    page.locator('#confirm').check()
    page.get_by_role('button', name='Simulate settlement').click()
    page.wait_for_function("document.querySelector('#t-settle').classList.contains('complete')")
    page.get_by_role('button', name='Test duplicate protection').click()
    page.wait_for_function("document.querySelector('#t-duplicate').classList.contains('complete')")
    assert 'Duplicate rejected by the local model' in page.locator('#status').inner_text()
    checks.append('Walkthrough settles once and rejects a duplicate')
    page.get_by_role('button', name='Verify receipt', exact=True).click()
    page.wait_for_function("document.querySelector('#t-verify').classList.contains('complete')")
    assert 'Not onchain evidence' in page.locator('#receipt-result').inner_text()
    with page.expect_download() as result:
        page.get_by_role('button', name='Download JSON receipt').click()
    result.value.save_as(str(out/'simulation-receipt.json'))
    bundle = json.loads((out/'simulation-receipt.json').read_text())
    assert bundle['schema'] == 'settleref.simulation.v1'
    checks.append('Simulation export is explicitly labelled and has a separate schema')
    page.screenshot(path=str(out/'desktop-complete.png'), full_page=True)
    page.locator('#receipt-file').set_input_files(str(out/'simulation-receipt.json'))
    page.wait_for_function("document.querySelector('#status').textContent.includes('Simulations are not accepted')")
    checks.append('Live receipt importer rejects simulation bundles')
    page.get_by_role('button', name='Arc payment', exact=True).click()
    page.wait_for_function("!document.querySelector('#deployment-notice').hidden")
    assert page.get_by_role('button', name='Sign and pay USDC').is_disabled()
    checks.append('Live mode cannot send without a verified deployment')
    page.get_by_role('button', name='Load example').click()
    page.locator('#reference').fill('<img src=x onerror=alert(1)>')
    page.get_by_role('button', name='Review instruction').click()
    page.wait_for_function("document.querySelector('#t-review').classList.contains('complete')")
    assert page.locator('#payment-summary img').count() == 0
    assert '<img src=x onerror=alert(1)>' in page.locator('#payment-summary').inner_text()
    checks.append('Untrusted invoice references render as text, not HTML')
    page.get_by_role('button', name='Local walkthrough').click()
    page.get_by_role('button', name='Load example').click()
    page.locator('#amount').fill('0.0000001')
    page.get_by_role('button', name='Review instruction').click()
    page.wait_for_function("document.querySelector('#status').textContent.includes('6 decimal places')")
    checks.append('UI rejects excessive precision instead of rounding')
    mobile = context.new_page()
    mobile.set_viewport_size({'width': 390, 'height': 844})
    mobile.goto('http://127.0.0.1:4173/', wait_until='networkidle')
    mobile.get_by_role('button', name='Load example').click()
    mobile.get_by_role('button', name='Review instruction').click()
    mobile.wait_for_function("document.querySelector('#t-review').classList.contains('complete')")
    assert mobile.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
    mobile.screenshot(path=str(out/'mobile-review.png'), full_page=True)
    checks.append('390px mobile layout has no horizontal overflow')
    assert not errors, errors
    checks.append('Desktop flow has no browser JavaScript errors')
    browser.close()
(out/'browser-tests.json').write_text(json.dumps({'passed': len(checks), 'checks': checks, 'scope': 'Real browser; local HTTP server; local simulation only. No live RPC or contract execution.'}, indent=2))
print(json.dumps({'passed':len(checks), 'checks':checks},indent=2))
